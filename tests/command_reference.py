"""Write the command reference in `docs/reference/` from the click command tree.

Run it from the repository root after changing a command, an option or a help
text:

    python tests/command_reference.py

It writes one page per top-level command or command group, and an index,
`README.md`, that lists the pages and the global options. Every page is made
from the same command tree that `--help` reads, so the reference cannot
disagree with the code. `tests/test_command_reference.py` fails when the
committed pages differ from what this module renders.

It lives in `tests/` and not in a `scripts/` folder because the sdist ships
`tests/` and mypy checks it, and the drift test imports it.
"""

from __future__ import annotations

import inspect
import re
from collections.abc import Iterable
from pathlib import Path

import click

from sopuli.cli import cli
from sopuli.invocation import global_options

ROOT = Path(__file__).resolve().parents[1]
REFERENCE = ROOT / "docs" / "reference"

PROGRAM = "sopuli"

#: The line at the top of every page.
GENERATED = (
    "<!-- Generated by tests/command_reference.py from the click command tree. "
    "Do not edit; run `python tests/command_reference.py` instead. -->"
)


def _global_names() -> frozenset[str]:
    """The parameter names of the global options.

    The root group declares a hidden copy of each one, so its parameters are
    the list. `--version` and `--help` belong to the root alone.
    """
    return frozenset(
        param.name
        for param in cli.params
        if param.name is not None and param.name not in {"version", "help"}
    )


GLOBAL_NAMES = _global_names()


#: A line that Markdown could read as a list item, a heading, a quote or a
#: heading's underline, rather than as the next line of a paragraph. Every
#: numbered line is refused, though only `1.` interrupts a paragraph: whether
#: the others make a list depends on where click's wrapping puts them.
_STRUCTURE = re.compile(r"^\s*(?:[-*+]\s|#{1,6}(?:\s|$)|>|\d+[.)](?:\s|$)|=+\s*$|-+\s*$)")

#: Text between backticks, which Markdown prints as written.
_CODE_SPAN = re.compile(r"`[^`]*`")

#: A `*`, or a `_` at the edge of a word, which Markdown can pair up as emphasis.
#: A `_` inside a word, as in `acme_app_user`, is left alone by GitHub.
_EMPHASIS = re.compile(r"\*|(?<!\w)_|_(?!\w)")


def _prose(text: str, where: str) -> str:
    """Help text, refused where Markdown would not show it as prose.

    The pages print help text as Markdown, so that its backticks show as code.
    A line that starts like a list item or a heading would change the page's
    structure, a `<` outside backticks can be swallowed as HTML, and a `*` or
    `_` can turn into italics. Rewording the help is the fix; escaping it here
    would make the page differ from `--help`.
    """
    for line in text.splitlines():
        if _STRUCTURE.match(line):
            raise ValueError(f"{where}: help line reads as Markdown structure: {line!r}")
    # A code span may run across a line break, so spans are found per paragraph.
    for paragraph in re.split(r"\n\s*\n", text):
        outside = _CODE_SPAN.sub("", " ".join(paragraph.split()))
        if "`" in outside:
            raise ValueError(f"{where}: help has an unpaired backtick: {paragraph!r}")
        if "<" in outside:
            raise ValueError(f"{where}: help has a `<` outside backticks: {paragraph!r}")
        if _EMPHASIS.search(outside):
            raise ValueError(f"{where}: help has a `*` or `_` outside backticks: {paragraph!r}")
    return text


def _help(command: click.Command, ctx: click.Context) -> str:
    """The command's help text, as `--help` shows it before click wraps it."""
    return _prose(inspect.cleandoc(command.help or ""), ctx.command_path)


def _usage(command: click.Command, ctx: click.Context) -> str:
    return " ".join([ctx.command_path, *command.collect_usage_pieces(ctx)])


def _metavar(param: click.Parameter) -> str:
    """The value's placeholder, as `--help` spells it.

    Built here rather than read from `make_metavar`, whose signature changed in
    click 8.2; `pyproject.toml` allows click 8.1.
    """
    if param.nargs != 1:
        raise ValueError(f"{param.name}: takes {param.nargs} values; extend the generator")
    if param.metavar is not None:
        return param.metavar
    if isinstance(param, click.Argument):
        name = (param.name or "").upper()
        return name if param.required else f"[{name}]"
    if isinstance(param.type, click.IntRange):
        return "INTEGER"  # the range itself is printed among the facts
    return param.type.name.upper()


def _bounds(kind: click.IntRange) -> str:
    """An integer range as words: `1 to 100`, `at least 1`, `less than 10`."""
    if kind.min is not None and kind.max is not None and not (kind.min_open or kind.max_open):
        return f"{kind.min} to {kind.max}"
    parts = []
    if kind.min is not None:
        parts.append(f"{'more than' if kind.min_open else 'at least'} {kind.min}")
    if kind.max is not None:
        parts.append(f"{'less than' if kind.max_open else 'at most'} {kind.max}")
    return ", ".join(parts)


def _default(option: click.Option, ctx: click.Context) -> str | None:
    """The default that `--help` shows, or None where it shows none.

    `--help` shows a default only for an option with `show_default`, and shows
    the string itself where `show_default` is one.
    """
    if isinstance(option.show_default, str):
        return option.show_default
    if not option.show_default:
        return None
    value = option.get_default(ctx, call=False)
    if isinstance(value, bool) or not isinstance(value, int | str):
        where = f"{ctx.command_path} {option.opts[0]}"
        raise ValueError(f"{where}: shows a {type(value).__name__} default; extend the generator")
    return str(value)


def _option_line(option: click.Option, ctx: click.Context) -> str:
    """One option as a list item: its names, its value, its facts, its help."""
    names = ", ".join(f"`{name}`" for name in [*option.opts, *option.secondary_opts])
    if option.is_flag:
        value = ""
    elif isinstance(option.type, click.Choice) and option.metavar is None:
        value = " `" + "|".join(str(choice) for choice in option.type.choices) + "`"
    else:
        value = f" `{_metavar(option)}`"

    facts: list[str] = []
    if isinstance(option.type, click.IntRange):
        facts.append(_bounds(option.type))
    default = _default(option, ctx)
    if default is not None:
        facts.append(f"default `{default}`")
    if option.multiple:
        facts.append("repeatable")
    if option.required:
        facts.append("required")
    said = f" ({', '.join(facts)})" if facts else ""
    where = f"{ctx.command_path} {option.opts[0]}"
    text = option.help or ""
    if re.search(r"\n\s*\n", text):
        # One list item holds one paragraph; a second would land under no option.
        raise ValueError(f"{where}: option help has more than one paragraph")

    return f"- {names}{value}{said}: {_prose(text, where)}".rstrip()


def _visible_options(command: click.Command) -> list[click.Option]:
    return [
        param
        for param in command.params
        if isinstance(param, click.Option) and not param.hidden and param.name != "help"
    ]


def _arguments(command: click.Command) -> list[str]:
    params = command.params
    return [f"- `{_metavar(param)}`" for param in params if isinstance(param, click.Argument)]


def _command_section(command: click.Command, ctx: click.Context, level: str) -> list[str]:
    """The heading, usage, help and options of one command that is not a group."""
    lines = [f"{level} {ctx.command_path}", "", "```", _usage(command, ctx), "```", ""]
    lines += [_help(command, ctx), ""]

    arguments = _arguments(command)
    if arguments:
        lines += ["Arguments:", "", *arguments, ""]

    options = _visible_options(command)
    own = [option for option in options if option.name not in GLOBAL_NAMES]
    if own:
        lines += ["Options:", "", *(_option_line(option, ctx) for option in own), ""]
    if any(option.name in GLOBAL_NAMES for option in options):
        lines += ["It also takes the [global options](README.md#global-options).", ""]
    return lines


def _subcommands(group: click.Group, ctx: click.Context) -> Iterable[tuple[str, click.Command]]:
    for name in group.list_commands(ctx):
        command = group.get_command(ctx, name)
        if command is not None and not command.hidden:
            yield name, command


def _leaves(group: click.Group, ctx: click.Context) -> Iterable[tuple[str, click.Command]]:
    """The commands of a top-level group, refusing a group inside it.

    The pages have one level of commands under each group. A nested group would
    otherwise be printed as a command, with its own commands left out.
    """
    for name, command in _subcommands(group, ctx):
        if isinstance(command, click.Group):
            raise ValueError(f"{ctx.command_path} {name} is a nested group; extend the generator")
        yield name, command


def _page(name: str, command: click.Command, root: click.Context) -> str:
    ctx = click.Context(command, info_name=name, parent=root)
    if not isinstance(command, click.Group):
        lines = [GENERATED, "", *_command_section(command, ctx, "#")]
    else:
        lines = [GENERATED, "", f"# {ctx.command_path}", "", _help(command, ctx), ""]
        for sub_name, sub in _leaves(command, ctx):
            sub_ctx = click.Context(sub, info_name=sub_name, parent=ctx)
            lines += _command_section(sub, sub_ctx, "##")
    return "\n".join(lines).rstrip() + "\n"


def _without_globals(root: click.Context) -> Iterable[str]:
    """The commands, spelled as typed, that take none of the global options."""
    for name, command in _subcommands(cli, root):
        ctx = click.Context(command, info_name=name, parent=root)
        leaves = (
            [(f"{name} {sub_name}", sub) for sub_name, sub in _leaves(command, ctx)]
            if isinstance(command, click.Group)
            else [(name, command)]
        )
        for spelled, leaf in leaves:
            if not any(option.name in GLOBAL_NAMES for option in _visible_options(leaf)):
                yield spelled


def _index(root: click.Context) -> str:
    lines = [
        GENERATED,
        "",
        "# Command reference",
        "",
        _help(cli, root),
        "",
        "Each page below covers one command, or one group of commands. It gives",
        "each command's usage line, its help text and its options. The pages are",
        "generated from the same definitions that `--help` reads.",
        "",
    ]
    for name, command in _subcommands(cli, root):
        # click cuts the summary at the limit, which could split a code span;
        # `_prose` refuses the unpaired backtick that would leave.
        summary = _prose(command.get_short_help_str(limit=200), f"{PROGRAM} {name}")
        lines.append(f"- [`{PROGRAM} {name}`]({name}.md): {summary}")
    lines.append("")

    # The options come from a command built with the decorator every verb uses,
    # so that no single verb decides what the list holds. It is never invoked.
    shown = click.command("global")(global_options(lambda **_: None))
    shown_ctx = click.Context(shown, info_name="global", parent=root)
    without = sorted(_without_globals(root))
    except_these = f" except {', '.join(f'`{name}`' for name in without)}" if without else ""
    lines += [
        "## Global options",
        "",
        f"Every command{except_these} takes these options, after the command name.",
        "",
        *(
            _option_line(option, shown_ctx)
            for option in _visible_options(shown)
            if option.name in GLOBAL_NAMES
        ),
        "",
    ]
    return "\n".join(lines).rstrip() + "\n"


def pages() -> dict[str, str]:
    """Every page of the reference, by file name."""
    root = click.Context(cli, info_name=PROGRAM)
    rendered = {"README.md": _index(root)}
    for name, command in _subcommands(cli, root):
        rendered[f"{name}.md"] = _page(name, command, root)
    return rendered


def main() -> None:
    """Write the pages, and remove a page that no command renders any more."""
    REFERENCE.mkdir(parents=True, exist_ok=True)
    rendered = pages()
    for stale in REFERENCE.glob("*.md"):
        if stale.name not in rendered:
            stale.unlink()
    for name, text in rendered.items():
        (REFERENCE / name).write_text(text, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
