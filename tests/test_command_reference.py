"""The committed command reference matches the command tree. Tier 0.

`docs/reference/` is generated by `tests/command_reference.py` from the same
click definitions that `--help` reads. A pull request that changes a command,
an option or a help text must regenerate it, and this test fails until it does.
The failure names the command to run.
"""

from __future__ import annotations

import pytest

from command_reference import REFERENCE, pages
from repo_files import requires_repo

REGENERATE = "run `python tests/command_reference.py` and commit docs/reference/"


def test_every_page_is_committed_and_none_is_extra() -> None:
    requires_repo(REFERENCE)
    committed = {path.name for path in REFERENCE.glob("*.md")}
    rendered = set(pages())
    assert committed == rendered, (
        f"missing: {sorted(rendered - committed)}, "
        f"no longer rendered: {sorted(committed - rendered)}; {REGENERATE}"
    )


@pytest.mark.parametrize(("name", "text"), sorted(pages().items()))
def test_page_matches_the_command_tree(name: str, text: str) -> None:
    page = REFERENCE / name
    requires_repo(page)
    assert page.read_text(encoding="utf-8") == text, (
        f"docs/reference/{name} is out of date; {REGENERATE}"
    )
